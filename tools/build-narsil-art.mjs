// Embeds the poses of baby Narsil that the work map shows, taken from a sibling narsilPet checkout:
// the still pictures (hooks/art/etapa1-<theme>.ts) into hooks/narsil-art.ts and the animated loops
// (hooks/art/anim/etapa1-<theme>.ts) into hooks/narsil-anim.ts.
//   node tools/build-narsil-art.mjs [path/to/narsilPet]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pet = resolve(process.argv[2] ?? join(root, '..', 'narsilPet'))
const POSES = ['parada', 'trabajando']
const THEMES = ['claro', 'oscuro']

function read(file, pose) {
  const text = readFileSync(join(pet, file), 'utf8')
  const m = text.match(new RegExp(String.raw`\n\s*${pose}: \{ src: '([^']+)', width: (\d+), height: (\d+) \}`))
  if (!m) throw new Error(`${file} has no pose ${pose}`)
  return `{ src: '${m[1]}', width: ${m[2]}, height: ${m[3]} }`
}

function build(out, header, file, prefix) {
  const lines = [...header, '']
  for (const pose of POSES) {
    for (const theme of THEMES) {
      lines.push(`export const ${prefix}${pose.toUpperCase()}_${theme.toUpperCase()}: Art = ${read(file(theme), pose)}`)
    }
  }
  writeFileSync(join(root, out), lines.join('\n') + '\n')
}

build(
  'hooks/narsil-art.ts',
  [
    "// Generated by tools/build-narsil-art.mjs from Narsil's still art (narsilPet hooks/art/etapa1-claro.ts",
    '// and etapa1-oscuro.ts): do not edit by hand.',
    'export type Art = { src: string; width: number; height: number }',
  ],
  theme => `hooks/art/etapa1-${theme}.ts`,
  '',
)
build(
  'hooks/narsil-anim.ts',
  [
    "// Generated by tools/build-narsil-art.mjs from Narsil's animated loops (narsilPet",
    '// hooks/art/anim/etapa1-claro.ts and etapa1-oscuro.ts): do not edit by hand.',
    "import type { Art } from './narsil-art'",
  ],
  theme => `hooks/art/anim/etapa1-${theme}.ts`,
  'ANIMADA_',
)
