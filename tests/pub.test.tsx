import { expect, test } from 'claude-code/testing'
import type { On } from 'claude-code'
import type { Engine } from 'claude-code/testing'

import { PUB, isFlutter, parsePub, pubSpecFor, rewritePub } from '../hooks/pub'

declare function setTimeout(fn: () => void, ms: number): unknown

const PANE = {
  plugin: 'narsil-check',
  component: 'Pane',
  requestId: 'narsil-check',
  props: { title: 'Narsil Check', isFocused: false, bodyColumns: 60, placement: 'dock', scroll: { offset: 0, bodyRows: 40 }, view: {} },
} as const

const PUBSPEC = `name: demo
description: A demo app.
version: 1.0.0+1

environment:
  sdk: ">=3.0.0 <4.0.0"

dependencies:
  flutter:
    sdk: flutter
  http: ^1.1.0 # networking
  provider: "6.0.5"
  intl:
    version: ">=0.18.0 <0.20.0"
    hosted: https://pub.dev
  local_pkg:
    path: ../local_pkg

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^3.0.0

flutter:
  uses-material-design: true
`

const PUBSPEC_LOCK = `# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  http:
    dependency: "direct main"
    description:
      name: http
      sha256: "abc"
      url: "https://pub.dev"
    source: hosted
    version: "1.1.2"
  provider:
    dependency: "direct main"
    description:
      name: provider
      url: "https://pub.dev"
    source: hosted
    version: "6.0.5"
  intl:
    dependency: "direct main"
    source: hosted
    version: "0.18.1"
  flutter_lints:
    dependency: "direct dev"
    source: hosted
    version: "3.0.1"
sdks:
  dart: ">=3.0.0 <4.0.0"
`

test('pubspec.yaml and pubspec.lock give each hosted package and its installed version', () => {
  expect(parsePub({ 'pubspec.yaml': PUBSPEC, 'pubspec.lock': PUBSPEC_LOCK })).toEqual([
    { name: 'http', spec: '^1.1.0', isDev: false, installed: '1.1.2' },
    { name: 'provider', spec: '6.0.5', isDev: false, installed: '6.0.5' },
    { name: 'intl', spec: '>=0.18.0 <0.20.0', isDev: false, installed: '0.18.1' },
    { name: 'flutter_lints', spec: '^3.0.0', isDev: true, installed: '3.0.1' },
  ])
  expect(isFlutter({ 'pubspec.yaml': PUBSPEC })).toBe(true)
  expect(isFlutter({ 'pubspec.yaml': 'name: cli\ndependencies:\n  args: ^2.4.0\n' })).toBe(false)
})

test('raising a constraint keeps its operator, its upper bound and every other byte', () => {
  expect(pubSpecFor('^1.1.0', '1.6.0')).toBe('^1.6.0')
  expect(pubSpecFor('>=0.18.0 <0.20.0', '0.19.0')).toBe('>=0.19.0 <0.20.0')
  expect(pubSpecFor('any', '2.0.0')).toBe('any')
  const up = (name: string, latest: string) =>
    ({ name, ecosystem: 'pub', spec: '', current: '', latest, bump: 'minor', isDev: false, group: 'bump', conflicts: [] as string[] }) as const
  expect(rewritePub(PUBSPEC, [up('http', '1.6.0'), up('provider', '6.1.5'), up('intl', '0.19.0'), up('flutter_lints', '3.0.2')])).toBe(
    PUBSPEC.replace('http: ^1.1.0 # networking', 'http: ^1.6.0 # networking')
      .replace('provider: "6.0.5"', 'provider: "6.1.5"')
      .replace('version: ">=0.18.0 <0.20.0"', 'version: ">=0.19.0 <0.20.0"')
      .replace('flutter_lints: ^3.0.0', 'flutter_lints: ^3.0.2'),
  )
})

test("pub.dev's answer gives the latest release and the repository", () => {
  const text = JSON.stringify({ latest: { version: '1.6.0', pubspec: { repository: 'https://github.com/dart-lang/http/tree/master/pkgs/http' } } })
  expect(PUB.latestOf(text)).toBe('1.6.0')
  expect(PUB.repoUrlOf(text)).toBe('https://github.com/dart-lang/http/tree/master/pkgs/http')
  expect(PUB.latestUrl('http')).toBe('https://pub.dev/api/packages/http')
  expect(PUB.importPattern('flutter_lints')).toBe(`['"]package:flutter_lints/`)
  expect(PUB.installArgv([], [], { 'pubspec.yaml': PUBSPEC })).toEqual([['flutter', 'pub', 'get']])
  expect(PUB.installArgv([], [], { 'pubspec.yaml': 'name: cli\n' })).toEqual([['dart', 'pub', 'get']])
})

function flutterApp(on: On, latest: Record<string, string>) {
  const files: Record<string, string> = { 'pubspec.yaml': PUBSPEC, 'pubspec.lock': PUBSPEC_LOCK }
  const store = new Map<string, unknown>()
  const keyOf = (path: string) => {
    const at = path.replace(/\\/g, '/')
    return Object.keys(files).find(name => at === name || at.endsWith(`/${name}`))
  }
  on('fs.exists', (_, e) => ({ value: keyOf(e.path) !== undefined }))
  on('fs.read', (_, e) => {
    const key = keyOf(e.path)
    if (key === undefined) throw new Error(`ENOENT: ${e.path}`)
    return { value: files[key] as string }
  })
  on('fs.write', (_, e) => {
    files[keyOf(e.path) ?? e.path] = e.text
    return { value: undefined }
  })
  on('http.fetch', (_, e) => {
    const version = latest[e.url.replace('https://pub.dev/api/packages/', '')]
    return {
      value: version
        ? { status: 200, ok: true, headers: {}, text: JSON.stringify({ latest: { version, pubspec: {} } }) }
        : { status: 404, ok: false, headers: {}, text: '{}' },
    }
  })
  on('store.get', (_, e) => ({ value: store.get(e.key) }))
  on('store.set', (_, e) => {
    store.set(e.key, e.value)
    return { value: undefined }
  })
  on('command.register', () => ({ value: { command: 'upgrades' } }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('ui.toast', () => ({ value: undefined }))
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  const ran: string[][] = []
  on('process.run', (_, e) => {
    ran.push([...e.argv])
    return { value: { exitCode: e.argv[0] === 'git' ? 1 : 0, stdout: '', stderr: '', isStdoutTruncated: false, isStderrTruncated: false } }
  })
  return { files, ran }
}

async function scanned($: Engine) {
  for (let i = 0; i < 100; i++) {
    const ui = await $.ui.mount({ ...PANE, surface: 'desktop' })
    const scanning = await ui.find({ type: 'Text', text: /Buscando/ })
    await ui.unmount()
    if (!scanning) return
    await new Promise<void>(resolve => setTimeout(() => resolve(), 10))
  }
}

test('a Flutter app lists its packages and the button raises pubspec.yaml and runs flutter pub get', async ($, on) => {
  const { files, ran } = flutterApp(on, { http: '1.6.0', provider: '6.1.5', intl: '0.20.2', flutter_lints: '6.0.0' })

  await $.session.start({ cwd: '/', surface: 'desktop', isInteractive: true })
  await scanned($)
  const ui = await $.ui.mount({ ...PANE, surface: 'desktop' })
  expect((await ui.find({ type: 'Text', text: /para actualizar/ }))?.text).toBe('4 para actualizar de 4 · 2 mayores · 2 triviales')
  // Below 1.0 a minor breaks: intl 0.18 -> 0.20 is a major.
  expect((await ui.find({ type: 'Text', text: /^intl/ }))?.text).toBe('intl 0.18.1 → 0.20.2')

  await ui.press({ key: 'upgrade-bumps' })
  expect(ran.filter(argv => argv[0] === 'flutter')).toEqual([['flutter', 'pub', 'get']])
  expect(files['pubspec.yaml']).toContain('http: ^1.6.0 # networking')
  expect(files['pubspec.yaml']).toContain('provider: "6.1.5"')
  expect(files['pubspec.yaml']).toContain('flutter_lints: ^3.0.0')
  await ui.unmount()
})
