const PANE = {
  plugin: 'narsil-check',
  component: 'Pane',
  requestId: 'narsil-check',
  props: { title: 'Narsil Check', isFocused: false, bodyColumns: 60, placement: 'dock', scroll: { offset: 0, bodyRows: 40 }, view: {} },
} as const

const CARGO_TOML = `[package]
name = "demo"
version = "0.1.0"
edition = "2021"

[dependencies]
serde = { version = "1.0.100", features = ["derive"] }
tokio = "1.30"   # async runtime
local = { path = "../local" }
"rand" = "0.8.5"

[dependencies.reqwest]
version = "0.11.20"
default-features = false

[dev-dependencies]
insta = "=1.34.0"

[target.'cfg(windows)'.dependencies]
winapi = "0.3.9"
`

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "serde"
version = "1.0.150"

[[package]]
name = "tokio"
version = "1.30.0"

[[package]]
name = "rand"
version = "0.7.3"

[[package]]
name = "rand"
version = "0.8.5"

[[package]]
name = "reqwest"
version = "0.11.20"

[[package]]
name = "insta"
version = "1.34.0"

[[package]]
name = "winapi"
version = "0.3.9"
`

test('the TOML reader reads tables, arrays of tables, inline tables and strings', () => {
  const t = parseToml(
    [
      'a = "x\\"y" # comment',
      "b = 'lit\\eral'",
      'c = [1, 2,',
      '  3]',
      'd = { e = true, "f.g" = 1.5 }',
      "[t.'q k'.s]",
      'v = """',
      'multi"""',
      '[[p]]',
      'n = 1',
      '[[p]]',
      'n = 2',
      '[p.meta]',
      'm = "on the last p"',
    ].join('\n'),
  )
  expect(t).toEqual({
    a: 'x"y',
    b: 'lit\\eral',
    c: [1, 2, 3],
    d: { e: true, 'f.g': 1.5 },
    t: { 'q k': { s: { v: 'multi' } } },
    p: [{ n: 1 }, { n: 2, meta: { m: 'on the last p' } }],
  })
})

test('a bare Cargo requirement is a caret range', () => {
  expect(cargoRange('1.30')).toBe('^1.30')
  expect(cargoRange('=1.34.0')).toBe('=1.34.0')
  expect(cargoRange('>=1.2, <1.5')).toBe('>=1.2 <1.5')
  expect(cargoSpecFor('1.30', '1.48.0')).toBe('1.48.0')
  expect(cargoSpecFor('=1.34.0', '1.40.1')).toBe('=1.40.1')
})

test('Cargo.toml and Cargo.lock give each crate and the version it resolved to', () => {
  expect(parseCargo({ 'Cargo.toml': CARGO_TOML, 'Cargo.lock': CARGO_LOCK })).toEqual([
    { name: 'serde', spec: '1.0.100', isDev: false, installed: '1.0.150' },
    { name: 'tokio', spec: '1.30', isDev: false, installed: '1.30.0' },
    // Cargo.lock holds rand 0.7.3 for another crate: this requirement's is 0.8.5.
    { name: 'rand', spec: '0.8.5', isDev: false, installed: '0.8.5' },
    { name: 'reqwest', spec: '0.11.20', isDev: false, installed: '0.11.20' },
    { name: 'winapi', spec: '0.3.9', isDev: false, installed: '0.3.9' },
    { name: 'insta', spec: '=1.34.0', isDev: true, installed: '1.34.0' },
  ])
  // A path dependency is not crates.io's.
  expect(parseCargo({ 'Cargo.toml': CARGO_TOML }).some(d => d.name === 'local')).toBe(false)
})

test('raising requirements in Cargo.toml leaves every other byte as it was', () => {
  const up = (name: string, latest: string) =>
    ({ name, ecosystem: 'cargo', spec: '', current: '', latest, bump: 'minor', isDev: false, group: 'bump', conflicts: [] as string[] }) as const
  const out = rewriteCargo(CARGO_TOML, [up('serde', '1.0.229'), up('tokio', '1.48.0'), up('reqwest', '0.11.27'), up('insta', '1.40.1')])
  expect(out).toBe(
    CARGO_TOML.replace('version = "1.0.100"', 'version = "1.0.229"')
      .replace('tokio = "1.30"', 'tokio = "1.48.0"')
      .replace('version = "0.11.20"', 'version = "0.11.27"')
      .replace('insta = "=1.34.0"', 'insta = "=1.40.1"'),
  )
})

test("crates.io's answer gives the latest stable release and the repository", () => {
  const text = JSON.stringify({ crate: { max_version: '2.0.0-rc.1', max_stable_version: '1.0.229', repository: 'https://github.com/serde-rs/serde' } })
  expect(CARGO.latestOf(text)).toBe('1.0.229')
  expect(CARGO.repoUrlOf(text)).toBe('https://github.com/serde-rs/serde')
  expect(CARGO.latestUrl('serde_json')).toBe('https://crates.io/api/v1/crates/serde_json')
  expect(CARGO.headers?.['user-agent']).toContain('narsil-check')
  expect(CARGO.importPattern('serde-json')).toBe('(extern crate[[:space:]]+serde_json|(^|[^[:alnum:]_])serde_json::)')
})

// A Rust project on disk and crates.io, standing for the engine.
function rust(on: On, latest: Record<string, string>) {
  const files: Record<string, string> = { 'Cargo.toml': CARGO_TOML, 'Cargo.lock': CARGO_LOCK }
  const store = new Map<string, unknown>()
  const keyOf = (path: string) => {
    const at = path.replace(/\\/g, '/')
    return Object.keys(files).find(name => at === name || at.endsWith(`/${name}`))
  }
  on('fs.exists', (_, e) => ({ value: keyOf(e.path) !== undefined }))
  on('fs.read', (_, e) => {
    const key = keyOf(e.path)
    if (key === undefined) throw new Error(`ENOENT: ${e.path}`)
    return { value: files[key] as string }
  })
  on('fs.write', (_, e) => {
    files[keyOf(e.path) ?? e.path] = e.text
    return { value: undefined }
  })
  on('http.fetch', (_, e) => {
    const version = latest[e.url.replace('https://crates.io/api/v1/crates/', '')]
    return {
      value: version
        ? { status: 200, ok: true, headers: {}, text: JSON.stringify({ crate: { max_stable_version: version } }) }
        : { status: 404, ok: false, headers: {}, text: '{}' },
    }
  })
  on('store.get', (_, e) => ({ value: store.get(e.key) }))
  on('store.set', (_, e) => {
    store.set(e.key, e.value)
    return { value: undefined }
  })
  on('command.register', () => ({ value: { command: 'upgrades' } }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('ui.toast', () => ({ value: undefined }))
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  const ran: string[][] = []
  on('process.run', (_, e) => {
    ran.push([...e.argv])
    // No git repository: nothing pending.
    return { value: { exitCode: e.argv[0] === 'git' ? 1 : 0, stdout: '', stderr: '', isStdoutTruncated: false, isStderrTruncated: false } }
  })
  return { files, ran }
}

async function scanned($: Engine) {
  for (let i = 0; i < 100; i++) {
    const ui = await $.ui.mount({ ...PANE, surface: 'desktop' })
    const scanning = await ui.find({ type: 'Text', text: /Buscando/ })
    await ui.unmount()
    if (!scanning) return
    await new Promise<void>(resolve => setTimeout(() => resolve(), 10))
  }
}

test('a Rust project lists its crates and the button raises Cargo.toml and updates Cargo.lock', async ($, on) => {
  const { files, ran } = rust(on, { serde: '1.0.229', tokio: '1.48.0', rand: '0.9.2', reqwest: '0.11.20', insta: '1.40.1', winapi: '0.3.9' })

  await $.session.start({ cwd: '/', surface: 'desktop', isInteractive: true })
  await scanned($)
  const ui = await $.ui.mount({ ...PANE, surface: 'desktop' })
  expect((await ui.find({ type: 'Text', text: /para actualizar/ }))?.text).toBe('4 para actualizar de 6 · 1 mayores · 3 triviales')
  expect((await ui.find({ type: 'Button', text: /^tokio/ }))?.text).toBe('tokio 1.30.0 → 1.48.0')
  // Below 1.0 a minor breaks: rand 0.8 -> 0.9 is a major.
  expect((await ui.find({ type: 'Button', text: /^rand/ }))?.text).toBe('rand 0.8.5 → 0.9.2')
  expect((await ui.find({ type: 'Button', text: /^insta/ }))?.text).toBe('insta 1.34.0 → 1.40.1 · dev')

  await ui.press({ key: 'upgrade-bumps' })
  expect(ran.filter(argv => argv[0] === 'cargo')).toEqual([['cargo', 'update', '-p', 'serde', '-p', 'tokio', '-p', 'insta']])
  expect(files['Cargo.toml']).toContain('serde = { version = "1.0.229", features = ["derive"] }')
  expect(files['Cargo.toml']).toContain('tokio = "1.48.0"   # async runtime')
  expect(files['Cargo.toml']).toContain('insta = "=1.40.1"')
  expect(files['Cargo.toml']).toContain('"rand" = "0.8.5"')
  await ui.unmount()
})
